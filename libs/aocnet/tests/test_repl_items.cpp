static std::vector<uint8_t> bytes_of_hex(const char* hex) {
    auto nib = [](char c) { return c <= '9' ? c - '0' : c - 'a' + 10; };
    std::vector<uint8_t> out;
    for (size_t i = 0; hex[i] && hex[i + 1]; i += 2) out.push_back(static_cast<uint8_t>(nib(hex[i]) << 4 | nib(hex[i + 1])));
    return out;
}

/// A bit string: what the test cuts and patches (LSB first, as on the wire).
struct Bits {
    std::vector<bool> b;
    Bits() = default;
    Bits(const std::vector<uint8_t>& bytes, size_t n) { for (size_t i = 0; i < n; ++i) b.push_back((bytes[i >> 3] >> (i & 7)) & 1); }
    explicit Bits(const BunchWriter& w) : Bits(w.bytes(), w.bit_pos()) {}
    size_t size() const { return b.size(); }
    std::vector<uint8_t> bytes() const {
        std::vector<uint8_t> out((b.size() + 7) / 8, 0);
        for (size_t i = 0; i < b.size(); ++i) out[i >> 3] |= static_cast<uint8_t>(b[i] ? 1 : 0) << (i & 7);
        return out;
    }
    Bits slice(size_t from, size_t n) const { Bits r; r.b.assign(b.begin() + from, b.begin() + from + n); return r; }
    void set(size_t at, uint64_t v, int n) { for (int i = 0; i < n; ++i) b[at + i] = (v >> i) & 1; }
    uint64_t get(size_t at, int n) const { uint64_t v = 0; for (int i = 0; i < n; ++i) v |= static_cast<uint64_t>(b[at + i] ? 1 : 0) << i; return v; }
    void insert(size_t at, uint64_t v, int n) { for (int i = 0; i < n; ++i) b.insert(b.begin() + at + i, (v >> i) & 1); }
    void erase(size_t at, size_t n) { b.erase(b.begin() + at, b.begin() + at + n); }
    bool operator==(const Bits& o) const { return b == o.b; }
};

static Bits bits_of_hex(const char* hex, size_t n) { return Bits(bytes_of_hex(hex), n); }

/// Runs `f(data, bytes, bits)` on a heap buffer of exactly the bytes the bits need: an over-read is an address sanitizer report.
template <class F>
static auto with_exact(const Bits& bits, F f) {
    const std::vector<uint8_t> v = bits.bytes();
    std::unique_ptr<uint8_t[]> exact(new uint8_t[v.empty() ? 1 : v.size()]);
    if (!v.empty()) std::memcpy(exact.get(), v.data(), v.size());
    return f(static_cast<const uint8_t*>(exact.get()), v.size(), bits.size());
}

static std::optional<ItemInstance> read_item_bits(const Bits& bits, size_t* consumed = nullptr) {
    return with_exact(bits, [&](const uint8_t* d, size_t bytes, size_t n) {
        PacketReader r(d, bytes, n);
        auto it = read_item_instance(r);
        if (consumed) *consumed = r.pos();
        return it;
    });
}

static std::optional<ItemStorageEvent> read_event_bits(const Bits& bits, size_t* consumed = nullptr) {
    return with_exact(bits, [&](const uint8_t* d, size_t bytes, size_t n) {
        PacketReader r(d, bytes, n);
        auto e = read_item_storage_event(r);
        if (consumed) *consumed = r.pos();
        return e;
    });
}

static Bits write_item_bits(const ItemInstance& it, bool* ok = nullptr) {
    BunchWriter w;
    const bool wrote = write_item_instance(w, it);
    if (ok) *ok = wrote;
    return Bits(w);
}

static Bits write_event_bits(const ItemStorageEvent& e, bool* ok = nullptr) {
    BunchWriter w;
    const bool wrote = write_item_storage_event(w, e);
    if (ok) *ok = wrote;
    return Bits(w);
}
