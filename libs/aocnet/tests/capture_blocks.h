/// The bytes of a hex string.
inline std::vector<uint8_t> bytes_of(const char* hex) {
    auto nib = [](char c) { return c <= '9' ? c - '0' : c - 'a' + 10; };
    std::vector<uint8_t> out;
    for (size_t i = 0; hex[i] && hex[i + 1]; i += 2) out.push_back(static_cast<uint8_t>(nib(hex[i]) << 4 | nib(hex[i + 1])));
    return out;
}

/// True when the first `n` bits of `a` and `b` are equal; else *first_diff is the first differing bit.
inline bool same_bit_range(const uint8_t* a, const uint8_t* b, size_t n, size_t* first_diff) {
    for (size_t i = 0; i < n; ++i) {
        if (((a[i >> 3] >> (i & 7)) & 1) != ((b[i >> 3] >> (i & 7)) & 1)) {
            if (first_diff) *first_diff = i;
            return false;
        }
    }
    return true;
}

