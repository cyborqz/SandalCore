static void test_confirmations() {
    std::printf("captured ClientHitConfirmations*: read, typed, written back bit for bit\n");
    Stats s;
    size_t bad = 0, bits_total = 0;
    std::string first_why;
    for (const cap::Call& c : cap::kConfirmations) {
        std::string why;
        bits_total += c.bits;
        if (!check_confirmation(c, &s, &why)) {
            ++bad;
            if (first_why.empty()) first_why = std::string(c.source) + ": " + why;
        }
    }
    CHECK(bad == 0, "every captured call reads to its last bit, parses, writes back the same bits and says what the Python decoder says");
    if (bad) std::printf("    first: %s\n", first_why.c_str());
    char msg[256];
    std::snprintf(msg, sizeof msg, "the sample: %zu calls (%zu reliable, %zu unreliable), %zu hits, %zu targets, %zu bits",
                  s.calls, s.reliable, s.unreliable, s.hits, s.targets, bits_total);
    CHECK(s.calls == std::size(cap::kConfirmations) && s.reliable > 0 && s.unreliable > 0, msg);
    CHECK(s.max_hits == 20 && s.max_targets == 9 && s.max_mods == 3 && s.max_hitmods == 9 && s.max_interrupts == 2,
          "it reaches the retail maxima: 20 hits a call, 9 targets a hit, 3 stat mods, 9 hit modifiers and 2 interrupts a target");
    CHECK(s.pvp && s.attempted && s.unset_source && s.null_comp && s.zero_normal && s.negative_x,
          "and pvp, an attempted interrupt, an unset Source, a null HitComp, a zero normal and a negative coordinate");
    CHECK(s.flags.count(0) && s.flags.count(1) && s.flags.count(2) && s.flags.count(3) && s.flags.count(4) && s.flags.count(5) &&
              s.flags.count(8) && s.flags.count(32) && s.flags.count(33) && s.flags.count(68) && s.flags.count(69) && s.flags.size() == 11,
          "eleven different Flags values: 0 1 2 3 4 5 8 32 33 68 69");
    CHECK(s.prediction.size() == 3 && !s.prediction.count({false, true}),
          "the prediction flags (autonomous, simulated) seen are 00, 10 and 11, never 01");

    // Capture 512 pkt 1325 is one hit with no target.
    for (const cap::Call& c : cap::kConfirmations) {
        if (std::string(c.source) != "0512 pkt 1325") continue;
        const auto call = read_call(rpc_of("AoCPlayerControllerBP_C", c.rpc), bits_of_hex(c.hex, c.bits));
        const auto hits = call ? parse_hit_confirmations(*call) : std::nullopt;
        CHECK(hits && hits->hits.size() == 1 && hits->hits[0].targets.empty() && c.bits == 1 + 11 + 15 + 8 * 77,
              "capture 512's call is one hit with no target: a send bit, 11 + 15 bits of counts and a 77-byte blob (616 bits)");
        CHECK(hits && hit_instance_bits(hits->hits[0]) == 615, "the blob itself is 615 bits: four int64, a UBOOL, two guids, the count, two UBOOLs");
    }
}

static void test_synthetic() {
    std::printf("hits no capture shows (built by the Python writer)\n");
    size_t bad = 0;
    std::string first_why;
    for (const cap::Call& c : cap::kSynthetic) {
        std::string why;
        if (!check_confirmation(c, nullptr, &why)) {
            ++bad;
            if (first_why.empty()) first_why = why;
        }
    }
    CHECK(bad == 0, "every synthetic call agrees with the Python writer and reader on every bit, and writes back the same bits");
    if (bad) std::printf("    first: %s\n", first_why.c_str());
    const auto call = read_call(rpc_of("AoCPlayerControllerBP_C", cap::kSynthetic[2].rpc), bits_of_hex(cap::kSynthetic[2].hex, cap::kSynthetic[2].bits));
    const auto hits = call ? parse_hit_confirmations(*call) : std::nullopt;
    CHECK(hits && hits->hits.size() == 1 && hits->hits[0].targets.size() == 3 && hits->hits[0].targets[0].stat_mods.size() == 10 &&
              hits->hits[0].targets[0].hit_mods.size() == 10 && hits->hits[0].targets[0].flags == 255 &&
              std::isnan(hits->hits[0].targets[0].impact_location.y) && std::signbit(hits->hits[0].targets[0].impact_location.z),
          "the limits case: 10 stat mods, 10 hit modifiers, Flags 255, a NaN and -0.0 survive");
}

