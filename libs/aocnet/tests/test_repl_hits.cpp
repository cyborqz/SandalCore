static void test_requests() {
    std::printf("captured RequestHitVerification_Server: read, typed, written back bit for bit\n");
    const schema::RpcSchema& rpc = rpc_of("UAoCAbilityComponent", "RequestHitVerification_Server");
    size_t bad = 0, inline_seen = 0, self = 0;
    size_t max_components = 0, zero_components = 0;
    std::string first_why;
    for (const cap::Call& c : cap::kRequests) {
        const Bits bits = bits_of_hex(c.hex, c.bits);
        std::string why;
        const auto call = read_call(rpc, bits, client_options());
        const auto req = call ? parse_hit_request(*call) : std::nullopt;
        if (!call || !req) why = "does not read or parse";
        else if (dump_request(*req) != c.dump) why = "dump differs:\n    " + dump_request(*req) + "\n    " + c.dump;
        else {
            const auto again = write_call(rpc, call->params, client_options());
            const auto built = hit_request_params(rpc, *req);
            if (!again || !(*again == bits)) why = "does not write back the same bits";
            else if (!built || !(*built == call->params)) why = "the typed form builds other parameters";
        }
        if (!why.empty()) {
            ++bad;
            if (first_why.empty()) first_why = std::string(c.source) + ": " + why;
            continue;
        }
        for (const HitComponentRef& comp : req->components) inline_seen += comp.inline_object ? 1 : 0;
        self += req->targeting_guid == kTargetingDefaultSelf ? 1 : 0;
        max_components = std::max(max_components, req->components.size());
        zero_components += req->components.empty() ? 1 : 0;
    }
    CHECK(bad == 0, "every captured request reads to its last bit, parses, writes back the same bits and says what the Python decoder says");
    if (bad) std::printf("    first: %s\n", first_why.c_str());
    CHECK(max_components == 9 && zero_components == 1 && inline_seen == 1 && self >= 1,
          "the sample: up to 9 components, one request with none, one with a component named in place, one naming Default_Self");
    // Without the inline option the in-place component is refused (a server's own parameters never are).
    size_t refused = 0;
    for (const cap::Call& c : cap::kRequests) {
        if (!read_call(rpc, bits_of_hex(c.hex, c.bits))) ++refused;
    }
    CHECK(refused == 1, "read without CodecOptions::inline_objects, exactly the one request that names a component in place is refused");
    // The in-place component is the pawn's CharacterMesh0 with its network checksum (value.h's InlineObject).
    for (const cap::Call& c : cap::kRequests) {
        const auto call = read_call(rpc, bits_of_hex(c.hex, c.bits), client_options());
        const auto req = call ? parse_hit_request(*call) : std::nullopt;
        if (!req || req->components.empty() || !req->components[0].inline_object) continue;
        const InlineObject& o = *req->components[0].inline_object;
        CHECK(o.flags == 5 && o.path == "CharacterMesh0" && o.checksum == 0xb876932fu,
              "that component: flags 5 (path and checksum), \"CharacterMesh0\", checksum 0xb876932f");
    }
    const RpcCall not_a_call;
    CHECK(!parse_hit_request(not_a_call) && !parse_hit_confirmations(not_a_call), "an empty call parses as nothing");
    const auto conf = read_call(rpc_of("AoCPlayerControllerBP_C", cap::kConfirmations[0].rpc), bits_of_hex(cap::kConfirmations[0].hex, cap::kConfirmations[0].bits));
    CHECK(conf && !parse_hit_request(*conf), "a confirmation is not a request");
    RpcCall undecoded = *conf;
    undecoded.decoded = false;
    CHECK(!parse_hit_confirmations(undecoded), "a call whose parameters did not decode is not acted on");
}

// ---- the emission ---------------------------------------------------------------------------------------------------------------

static void test_emission() {
    std::printf("ClientHitConfirmations* on a PlayerController\n");
    const schema::ClassSchema& pc_schema = schema_named("AoCPlayerControllerBP_C");
    Actor pc;
    pc.guid = FIntrepidNetworkGUID{588076, 60, 0};
    pc.obj.schema = &pc_schema;
    ExportAcks acks;
    const cap::Call& sample = cap::kConfirmations[10];   // capture 59: an attempted interrupt
    const auto call = read_call(rpc_of("AoCPlayerControllerBP_C", sample.rpc), bits_of_hex(sample.hex, sample.bits));
    const auto hits = call ? parse_hit_confirmations(*call) : std::nullopt;
    CHECK(hits.has_value(), "a captured call to send back");
    if (!hits) return;
    for (const bool reliable : {true, false}) {
        const auto e = client_hit_confirmations(pc, *hits, reliable, acks);
        CHECK(e && e->reliable == reliable, reliable ? "ClientHitConfirmationsReliable is reliable (function flags 0x01020cc0)"
                                                    : "ClientHitConfirmations is unreliable (function flags 0x01020c40)");
        if (!e) continue;
        const auto blocks = read_content_blocks(e->payload.data(), e->payload.bit_pos(), 0, true);
        CHECK(blocks && blocks->size() == 1 && (*blocks)[0].header.is_actor, "one block, on the PlayerController");
        if (!blocks || blocks->empty()) continue;
        size_t pos = (*blocks)[0].payload_pos;
        const auto calls = read_rpc_fields(pc_schema, e->payload.data(), pos + (*blocks)[0].payload_bits, pos);
        const char* name = reliable ? "ClientHitConfirmationsReliable" : "ClientHitConfirmations";
        CHECK(calls && calls->size() == 1 && (*calls)[0].decoded && std::string((*calls)[0].rpc->name) == name,
              "the field loop holds that one RPC, decoded");
        const auto back = calls && !calls->empty() ? parse_hit_confirmations((*calls)[0]) : std::nullopt;
        CHECK(back && *back == *hits, "and its hits read back equal");
    }
    Actor bare;
    bare.obj.schema = &schema_named("PlayerPawn_C");   // a class without the RPC
    CHECK(!client_hit_confirmations(bare, *hits, true, acks), "an actor whose class has no such RPC gets nothing");
    HitConfirmations too_many;
    too_many.hits.resize(kMaxHitConfirmations + 1);
    CHECK(!client_hit_confirmations(pc, too_many, true, acks), "hits over the exe's limit of 1,000 are not sent");
}

