static std::optional<HitInstance> read_blob(const Bits& bits) {
    return with_exact(bits, [&](const uint8_t* d, size_t bytes, size_t) { return deserialize_hit_instance(d, bytes); });
}

static std::optional<HitConfirmations> read_struct_bits(const Bits& bits) {
    return with_exact(bits, [&](const uint8_t* d, size_t bytes, size_t n) {
        PacketReader r(d, bytes, n);
        return read_hit_confirmations(r);
    });
}

static Bits blob_bits(const HitInstance& h) {
    const auto blob = serialize_hit_instance(h);
    return blob ? Bits(*blob, blob->size() * 8) : Bits();
}

/// The offsets of a sample blob's fields (two identical targets, each with one stat mod, two interrupts and one hit modifier).
struct Layout {
    static constexpr size_t pvp = 256, instigator = 288, source = 416, target_count = 544, first_target = 551;
    static constexpr size_t target_stat_count = 128 + 192 + 192, target_stats = target_stat_count + 5,
                            target_interrupt_count = target_stats + 128, target_attempted = target_interrupt_count + 32 + 128,
                            target_flags = target_attempted + 32, target_hitmod_count = target_flags + 8,
                            target_size = target_hitmod_count + 5 + 192;
};

static void test_refusals() {
    std::printf("hostile input, a field at a time\n");
    const HitInstance good = sample_hit();
    const Bits blob = blob_bits(good);
    CHECK(blob.size() == (hit_instance_bits(good) + 7) / 8 * 8 && read_blob(blob) && *read_blob(blob) == good,
          "a sample hit with two targets serializes and reads back");
    CHECK(hit_instance_bits(good) == Layout::first_target + 2 * Layout::target_size + 64 &&
              blob.get(Layout::target_count, 7) == 2,
          "its layout is the documented one (the second target starts where the first ends)");
    {
        Bits b = blob;
        b.set(Layout::target_count, 41, 7);
        CHECK(!read_blob(b), "41 targets (the exe clamps to 40)");
        b.set(Layout::target_count, 127, 7);
        CHECK(!read_blob(b), "127 targets: the count is checked against the bits left");
    }
    {
        Bits b = blob;
        b.set(Layout::pvp, 2, 32);
        CHECK(!read_blob(b), "bPvPForceFlag of 2: a UBOOL above 1 is an archive error");
        b = blob;
        b.set(Layout::first_target + Layout::target_attempted, 2, 32);
        CHECK(!read_blob(b), "bAttemptedInterrupt of 2");
        b = blob;
        b.set(hit_instance_bits(good) - 64, 0xffffffffu, 32);
        CHECK(!read_blob(b), "bPredictedOnAutonomous of 0xffffffff");
    }
    {
        Bits b = blob;
        b.set(Layout::first_target + Layout::target_stat_count, 11, 5);
        CHECK(!read_blob(b), "11 stat mods (the exe clamps to 10)");
        b = blob;
        b.set(Layout::first_target + Layout::target_hitmod_count, 11, 5);
        CHECK(!read_blob(b), "11 hit modifiers");
        b = blob;
        b.set(Layout::first_target + Layout::target_interrupt_count, 65, 32);
        CHECK(!read_blob(b), "65 interrupts (our bound; the exe's array operator has none below 0x200000)");
        b.set(Layout::first_target + Layout::target_interrupt_count, 0x80000000u, 32);
        CHECK(!read_blob(b), "a negative interrupt count");
        b.set(Layout::first_target + Layout::target_interrupt_count, 0x7fffffff, 32);
        CHECK(!read_blob(b), "an interrupt count of 2^31 - 1 buys nothing");
    }
    {
        Bits b = blob;
        b.append(0, 8);
        CHECK(!read_blob(b), "a whole extra byte after the content: the exe's writer ends the blob in its last byte");
        const size_t content = hit_instance_bits(good);
        if (content % 8) {
            b = blob;
            b.set(content, 1, 1);
            CHECK(!read_blob(b), "a padding bit that is not zero");
        } else {
            std::printf("  [skip] the sample has no padding bits\n");
        }
        bool all_refused = true;
        for (size_t cut = 0; cut < blob.size() / 8; ++cut) {
            if (read_blob(blob.slice(0, cut * 8))) all_refused = false;
        }
        CHECK(all_refused, "every truncation of the blob to fewer bytes is refused");
        CHECK(!deserialize_hit_instance(nullptr, 100) && !deserialize_hit_instance(blob.bytes().data(), kMaxHitBlobBytes + 1),
              "no data, and a blob over 10,000 bytes");
    }
// (C | O | A) (C-Y-B)

    // The struct around the blobs.
    HitConfirmations c;
    c.hits = {good, good};
    BunchWriter w;
    CHECK(write_hit_confirmations(w, c), "two hits write");
    const Bits whole(w);
    CHECK(whole.size() == 11 + 2 * (15 + blob.size()) && whole.get(0, 11) == 2 && whole.get(11, 15) == blob.size() / 8,
          "as an 11-bit count and, per hit, a 15-bit length and the bytes");
    {
        const auto back = read_struct_bits(whole);
        CHECK(back && *back == c, "and read back equal");
        Bits b = whole;
        b.set(0, 1001, 11);
        CHECK(!read_struct_bits(b), "1,001 hits (the exe clamps to 1,000)");
        b.set(0, 2047, 11);
        CHECK(!read_struct_bits(b), "2,047 hits: checked against the bits left");
        b = whole;
        b.set(11, kMaxHitBlobBytes + 1, 15);
        CHECK(!read_struct_bits(b), "a blob length of 10,001");
        b.set(11, 32767, 15);
        CHECK(!read_struct_bits(b), "a blob length of 32,767");
        b = whole;
        b.set(11, blob.size() / 8 - 1, 15);
        CHECK(!read_struct_bits(b), "a length one byte short: the blob is cut and the next length misreads");
        b = whole;
        b.set(11, blob.size() / 8 + 1, 15);
        CHECK(!read_struct_bits(b), "a length one byte long");
        bool all_refused = true;
        for (size_t cut = 0; cut < whole.size(); ++cut) {
            if (read_struct_bits(whole.slice(0, cut))) all_refused = false;
        }
        CHECK(all_refused, "every truncation of the struct is refused");
        CHECK(!read_struct_bits(Bits()), "an empty buffer");
    }
    {   // the writer's side
        HitConfirmations bad;
        bad.hits = {good};
        bad.hits[0].targets.assign(41, HitTarget{});
        BunchWriter wb;
        CHECK(!write_hit_confirmations(wb, bad) && wb.bit_pos() == 0 && !hit_confirmations_fit(bad), "41 targets are not written");
        bad.hits = {good};
        bad.hits[0].targets[0].stat_mods.assign(11, HitStatMod{});
        CHECK(!write_hit_confirmations(wb, bad), "11 stat mods are not written");
        bad.hits = {good};
        bad.hits[0].targets[0].hit_mods.assign(11, HitModInst{});
        CHECK(!write_hit_confirmations(wb, bad), "11 hit modifiers are not written");
        bad.hits = {good};
        bad.hits[0].targets[0].interrupts.assign(65, 0);
        CHECK(!write_hit_confirmations(wb, bad), "65 interrupts are not written");
        bad.hits.assign(kMaxHitConfirmations + 1, HitInstance{});
        CHECK(!write_hit_confirmations(wb, bad), "1,001 hits are not written");
        HitInstance huge;
        HitTarget fat;
        fat.stat_mods.assign(kMaxHitStatMods, HitStatMod{});
        fat.hit_mods.assign(kMaxHitHitMods, HitModInst{});
        huge.targets.assign(kMaxHitTargets, fat);
        CHECK(hit_instance_bits(huge) / 8 > kMaxHitBlobBytes && !hit_instance_fits(huge) && !serialize_hit_instance(huge),
              "a hit that would not fit 10,000 bytes (40 full targets) is not written");
        HitConfirmations maximal;
        maximal.hits.assign(kMaxHitConfirmations, HitInstance{});
        BunchWriter wm;
        CHECK(write_hit_confirmations(wm, maximal) && wm.bit_pos() == 11 + 1000 * (15 + 8 * 77), "1,000 empty hits are written: the exe's limit");
        const Bits mb(wm);
        const auto mr = read_struct_bits(mb);
        CHECK(mr && mr->hits.size() == 1000, "and read back");
        CHECK(!struct_accepts("FSerializedClientHitConfirmations", Value::u64(1)) &&
                  struct_accepts("FSerializedClientHitConfirmations", Value(c)) && is_known_struct("FSerializedClientHitConfirmations") &&
                  !zero_struct("FSerializedClientHitConfirmations"),
              "the codec registry knows the struct, accepts only its value type and has no zero value for it");
    }
}

// ---- fuzz ------------------------------------------------------------------------------------------------------------------------

static void test_fuzz() {
    std::printf("hostile payloads, a seeded fuzz of the captures\n");
    struct Seed {
        const schema::RpcSchema* rpc;
        Bits                     bits;
        bool                     request;
    };
    std::vector<Seed> seeds;
    for (const cap::Call& c : cap::kConfirmations) seeds.push_back({&rpc_of("AoCPlayerControllerBP_C", c.rpc), bits_of_hex(c.hex, c.bits), false});
    for (const cap::Call& c : cap::kSynthetic) seeds.push_back({&rpc_of("AoCPlayerControllerBP_C", c.rpc), bits_of_hex(c.hex, c.bits), false});
    for (const cap::Call& c : cap::kRequests)
        seeds.push_back({&rpc_of("UAoCAbilityComponent", c.rpc), bits_of_hex(c.hex, c.bits), true});
// ~ CoA - C Y B ~

    Rng rng(0x9e3779b97f4a7c15ull);
    size_t reads = 0, decoded = 0, typed = 0, rewritten = 0, same = 0;
    const auto start = std::chrono::steady_clock::now();
    const auto run = [&](const Seed& s, const Bits& m) {
        ++reads;
        const CodecOptions opts = client_options();
        const auto call = with_exact(m, [&](const uint8_t* d, size_t bytes, size_t n) -> std::optional<RpcCall> {
            (void)bytes;
            size_t pos = 0;
            auto p = read_rpc_params(*s.rpc, d, n, pos, opts);
            if (!p) return std::nullopt;
            RpcCall c;
            c.rpc = s.rpc;
            c.params = std::move(*p);
            c.decoded = true;
            return c;
        });
        if (!call) return;
        ++decoded;
        // Whatever reads writes back to a payload that reads equal.
        const auto out = write_call(*s.rpc, call->params, opts);
        if (!out) return;
        ++rewritten;
        const auto second = read_call(*s.rpc, *out, opts);
        if (second && second->params == call->params) ++same;
        if (s.request) {
            const auto req = parse_hit_request(*call);
            if (req) {
                ++typed;
                const auto built = hit_request_params(*s.rpc, *req);
                if (!built || !(*built == call->params)) std::printf("    a request builds other parameters\n");
            }
        } else {
            const auto hits = parse_hit_confirmations(*call);
            if (hits) ++typed;
        }
    };
    for (const Seed& s : seeds) {
        const size_t n = s.bits.size();
        run(s, s.bits);
        for (int round = 0; round < 120; ++round) {   // bit flips
            Bits m = s.bits;
            const int flips = 1 + static_cast<int>(rng.below(4));
            for (int i = 0; i < flips; ++i) {
                const size_t at = rng.below(n);
                m.b[at] = !m.b[at];
            }
            run(s, m);
        }
        for (int round = 0; round < 60; ++round) run(s, s.bits.slice(0, 1 + rng.below(n)));   // cut short
        for (int round = 0; round < 40; ++round) {                                            // the tail replaced by noise
            Bits m = s.bits;
            for (size_t bit = rng.below(n); bit < n; ++bit) {
                if (rng.next() & 1) m.b[bit] = !m.b[bit];
            }
            run(s, m);
        }
        for (int round = 0; round < 60; ++round) {   // special words at random byte-aligned places
            static const uint64_t words[] = {0, 1, 2, 0xff, 0xffff, 0x7fffffff, 0x80000000u, 0xffffffffu, 0xffffffffffffffffull};
            Bits m = s.bits;
            const size_t at = rng.below(n);
            const uint64_t w = words[rng.below(std::size(words))];
            for (int i = 0; i < 32 && at + i < n; ++i) m.b[at + i] = (w >> i) & 1;
            run(s, m);
        }
    }
    const double secs = std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
    std::printf("    %zu reads, %zu decoded, %zu typed, %zu written back, %zu reading back equal, %.2f s\n", reads, decoded, typed, rewritten, same, secs);
    CHECK(reads > 10000 && decoded > 0 && rewritten == decoded && same == rewritten,
          "mutated calls: none crashes, every call that decodes writes back, and what it writes back reads equal");
    CHECK(secs < 60, "and none takes long");
}

int main() {
    test_confirmations();
    test_synthetic();
    test_requests();
    test_emission();
    test_refusals();
    test_fuzz();
    std::printf("\n%d passed, %d failed\n", g_pass, g_fail);
    return g_fail == 0 ? 0 : 1;
}
