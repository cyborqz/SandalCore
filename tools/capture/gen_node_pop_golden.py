"""server/worldd/tests/node_pop_golden.h: the towns' people as an independent Python port counts them (Nodes 1, stage 3b).

worldd selects a node's NPCs with spawns/node_population.cpp (select_node_spawns) over the population chain and the node tables of content.db.  tools/capture/node_pop_oracle.py does the
same from content.db in Python (pop_oracle.py's data and filter).  This script runs it for every city node inside the Riverlands (the 10 nodes of the Verra world map whose location
the region's footprint holds and that have a layout) at each of the seven node levels, with the spawn context the tests use (Kaelar, Summer, clear, hour 11, the node's own id, type,
level, biome and zone; the Layout and BuildingLevelSpawn sources running; the siege tags any-of; the humanoids a retail capture opened shown), and writes what it counted: the sets and
points of the layout and of the buildings, the NPCs spawned from each, the points dropped by reason and without a template, the NPCs by Blueprint and a digest of the whole list.
tests/test_worldd_node_pop.cpp compares worldd's own selection to it.

    python tools/capture/gen_node_pop_golden.py [--content-db PATH] [--motion PATH]          # rewrite the header
    python tools/capture/gen_node_pop_golden.py --check                                       # write nothing, exit 1 on a change

Inputs: dist/content/content.db, dist/content/npc_motion.tsv, spawns/area_spawns.h (the NPC templates retail opened), fixtures/region/*.json.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import node_pop_oracle as N  # noqa: E402
import pop_oracle as P  # noqa: E402

ROOT = P.ROOT
HEADER = os.path.join(ROOT, 'server', 'worldd', 'tests', 'node_pop_golden.h')
SPAWNS = os.path.join(ROOT, 'server', 'worldd', 'spawns', 'area_spawns.h')
HOUR = 11.0
MAP = 'Verra_World_Master'


def cases(d, nd, region):
    """[(node record name, level, stage counts, filtered, byarch, spawned)] for every node inside the region."""
    base = P.Context(HOUR)
    shown = N.captured_leaves(d)
    out = []
    for n in sorted(nd.nodes.values(), key=lambda x: x['rank']):
        if n['map'] != MAP or not n['layout'] or not region.contains(n['x'], n['y']):
            continue
        for level in range(7):
            st, filt, by, spawned = N.select_node(d, nd, n, level, base, region.contains, shown)
            out.append((n['name'], level, st, filt, by, spawned))
    return out


def render(results):
    out = ['''// ============================================================================
//  server/worldd/tests/node_pop_golden.h
//
//  GENERATED by tools/capture/gen_node_pop_golden.py from tools/capture/node_pop_oracle.py (an independent Python port of the towns' people); do not edit.
//
//  The people of every city node inside the Riverlands at each node level (0 to 6), for the spawn context of the tests (Kaelar, Summer, clear, hour 11, the node's own id, type, level,
//  biome and zone, the Layout and BuildingLevelSpawn sources running, the siege tags any-of, the humanoids a retail capture opened shown): the sets and points of the layout (L) and of the
//  buildings (B), the NPCs spawned from each, the points dropped for want of a template or an asset or for being outside the area, the points dropped by the spawn filter by reason, the
//  NPCs by Blueprint, and a digest of the whole list (the multiset of x and y in cm, level and Blueprint, FNV-1a each, summed).
// ============================================================================
#pragma once

#include <cstddef>
#include <cstdint>

namespace aoc::worldd::tests {

struct NodePopCase {
    const char* node;          // the record name
    int         level;         // ENodeLevel
    unsigned    sets_layout, sets_building, points_layout, points_building;
    unsigned    spawned_layout, spawned_building;
    unsigned    no_template, no_asset, outside;
    const char* filtered;      // "Why:count;Why:count" by name
    const char* blueprints;    // "Blueprint:count;..." by name
    uint64_t    digest;
};

inline constexpr NodePopCase kNodePopCases[] = {''']
    for name, level, st, filt, by, spawned in results:
        out.append('    {"%s", %d, %d, %d, %d, %d, %d, %d, %d, %d, %d,' % (name, level, st['sets_layout'], st['sets_building'], st['points_layout'], st['points_building'],
                                                                      st['spawned_layout'], st['spawned_building'], st['no_template'], st['no_asset'], st['outside']))
        out.append('     "%s",' % ';'.join('%s:%d' % (k, filt[k]) for k in sorted(filt)))
        out.append('     "%s",' % ';'.join('%s:%d' % (k, by[k]) for k in sorted(by)))
        out.append('     %dull},' % N.digest(spawned))
    out.append('};\n')
    out.append('inline constexpr size_t kNodePopCaseCount = sizeof(kNodePopCases) / sizeof(kNodePopCases[0]);\n')
    out.append('}  // namespace aoc::worldd::tests\n')
    return '\n'.join(out)
# -- C-Y-B & C-O-A --


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--content-db', default=os.environ.get('AOC_CONTENT_DB') or os.path.join(ROOT, 'dist', 'content', 'content.db'))
    ap.add_argument('--motion', default=os.path.join(ROOT, 'dist', 'content', 'npc_motion.tsv'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    for p in (a.content_db, a.motion):
        if not os.path.exists(p):
            sys.exit('not found: ' + p)
    d = P.Data(a.content_db, a.motion, SPAWNS)
    nd = N.NodeData(d.db)
    region = P.Region()
    results = cases(d, nd, region)
    nodes = sorted({r[0] for r in results})
    print('%d nodes inside the Riverlands, %d cases' % (len(nodes), len(results)))
    for name, level, st, filt, by, spawned in results:
        if level in (0, 3, 4):
            print('  %-42s L%d: %4d NPCs (%d layout + %d building)' % (name, level, st['spawned'], st['spawned_layout'], st['spawned_building']))
    text = render(results)
    old = open(HEADER, newline='').read() if os.path.exists(HEADER) else None
    same = old is not None and old.replace('\r\n', '\n') == text
    if a.check:
        print('node_pop_golden.h: ' + ('unchanged' if same else 'WOULD CHANGE'))
        sys.exit(0 if same else 1)
    if same:
        print('node_pop_golden.h: unchanged')
        return
    crlf = old is not None and '\r\n' in old
    with open(HEADER, 'w', newline='') as f:
        f.write(text.replace('\n', '\r\n') if crlf else text)
    print('node_pop_golden.h: updated')


if __name__ == '__main__':
    main()
