"""server/worldd/combat/npc_kits.h: what the retail NPCs fight with (plan E1, stage 3).

The abilities each creature kind uses against a player, from the retail captures as the combat research read them (research/combat/picks.json, tables
npc_kits, type_stats_onme, ability_windup): for every Blueprint class the captures opened, the abilities of its open's AbilityComponent
(ReplicatedRecordsToLoad) with how often the captures saw each one cast on a player, how long after the cast the hit confirmation came (the windup), and how far
from the player the NPC was at the cast (the range it fights at).  The AI (npc/ai/npc_ai.h) picks among them by their weights; a kind the captures did not
open fights with a level-scaled generic slash.

    python tools/capture/gen_npc_kits.py --picks PATH            # rewrite the header from the research's picks.json
    python tools/capture/gen_npc_kits.py --picks PATH --check    # write nothing, exit 1 on a change

PATH is research/combat/picks.json of the stage 3 research folder (it is not in the repository; AOC_COMBAT_PICKS names it too).
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'server', 'worldd', 'combat', 'npc_kits.h')

DEFAULT_WINDUP_MS = 500      # an ability with no measured windup
DEFAULT_RANGE_CM = 250       # and no measured range


def kits_of(picks):
    tables = picks['tables']
    kits = tables['npc_kits']
    windup = tables.get('ability_windup', {})
    typed = tables.get('type_stats_onme', {})
    # type_stats_onme is keyed by the family ("Rabid"), npc_kits by the Blueprint class ("Rabid_C", "Bandit_Raider_Dunir_C")
    out = {}
    for cls, kit in sorted(kits.items()):
        leaf = cls[:-2] if cls.endswith('_C') else cls
        ty = None
        for fam in (leaf, leaf.split('_')[0], '_'.join(leaf.split('_')[:2])):
            if fam in typed:
                ty = typed[fam]
                break
        per_ability = {}
        interval = 0
        if ty:
            if ty.get('interval'):
                interval = int(ty['interval'][1])
            for a in ty['abilities']:
                dist = a.get('dist')
                rng = 0
                for r in a.get('static', {}).get('range', []):
                    rng = max(rng, int(r[1]))
                if rng == 0 and dist:
                    rng = int(dist[1])
                per_ability[a['ability']] = rng
        abilities = []
        for name, n in kit['abilities']:
            w = windup.get(name)
            wu = DEFAULT_WINDUP_MS
            if w and w.get('dt') and w['dt'][1] > 0:
                wu = int(w['dt'][1])
            abilities.append((name, int(n), wu, per_ability.get(name, 0) or DEFAULT_RANGE_CM))
        abilities.sort(key=lambda a: (-a[1], a[0]))
        out[leaf] = (abilities, interval)
    return out

# C-O-A + Cyb

def render(kits):
    lines = []
    w = lines.append
    w('// ============================================================================')
    w('//  combat/npc_kits.h: GENERATED by tools/capture/gen_npc_kits.py from the stage 3 combat research (picks.json); do not edit.')
    w('//')
    w('//  The abilities each creature Blueprint of the retail captures fought a player with: the uses seen (a weight), the windup (ms from the cast to the hit')
    w('//  confirmation, the median) and the range (cm, the farthest the ability reaches by its data, else the median distance of the cast).  `interval_ms` is the')
    w('//  median gap between one creature kind\'s casts (0: not measured).')
    w('// ============================================================================')
    w('#pragma once')
    w('')
    w('#include <cstddef>')
    w('')
    w('namespace aoc::worldd::combat::npc_kits {')
    w('')
    w('struct KitAbility {')
    w('    const char* name;')
    w('    int         uses;')
    w('    int         windup_ms;')
    w('    int         range_cm;')
    w('};')
    w('struct Kit {')
    w('    const char*       blueprint;   // the Blueprint class without "_C"')
    w('    const KitAbility* abilities;')
    w('    size_t            count;')
    w('    int               interval_ms;')
    w('};')
    w('')
    for i, (leaf, (abilities, interval)) in enumerate(kits.items()):
        w('inline constexpr KitAbility kAbilities%d[] = {' % i)
        for name, n, wu, rng in abilities:
            w('    {"%s", %d, %d, %d},' % (name, n, wu, rng))
        w('};')
    w('')
    w('inline constexpr Kit kKits[] = {')
    for i, (leaf, (abilities, interval)) in enumerate(kits.items()):
        w('    {"%s", kAbilities%d, %d, %d},' % (leaf, i, len(abilities), interval))
    w('};')
    w('inline constexpr size_t kKitCount = %d;' % len(kits))
    w('')
    w('}  // namespace aoc::worldd::combat::npc_kits')
    w('')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--picks', default=os.environ.get('AOC_COMBAT_PICKS'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    if not a.picks:
        print('gen_npc_kits: --picks (or AOC_COMBAT_PICKS) names research/combat/picks.json', file=sys.stderr)
        return 2
    with open(a.picks, encoding='utf-8') as f:
        picks = json.load(f)
    text = render(kits_of(picks))
    if a.check:
        with open(OUT, encoding='utf-8', newline='') as f:
            have = f.read().replace('\r\n', '\n')
        if have != text:
            print('gen_npc_kits: %s is not what the research gives' % OUT, file=sys.stderr)
            return 1
        print('gen_npc_kits: up to date')
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
