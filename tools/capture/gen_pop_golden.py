"""server/worldd/tests/pop_golden_region.h: the Riverlands' population counts, from an independent port of the selection (G1, stage 1, Part B).

worldd selects the region's NPCs with spawns/population.cpp and the spawn filter (E1 stage 3) over the 401-rectangle footprint of spawns/region_data.h.  tools/capture/pop_oracle.py
does the same selection from content.db in Python, from the JSON the region generator reads (not from the header).  This script runs it twice, for the spawn context the
tests use (Wilderness, Kaelar, Summer, clear, hour 11, only Guard_Soldier among the humanoids), and writes what it counted:

    kGoldenPlain   no zone of influence: a PopulationFilter that names zones never passes.  This is the research's pop.py and E1's rule applied to the whole region
                   (10,554 NPCs, 22,122 points on the exact footprint; the 10,850 and 22,421 of the research were the 55 km2 chunk upper bound): the counts that worldd must give with the zone rule off.
    kGoldenZoi     the point's own zone of influence answers the filter's zones (the 11 filters that name Aela, Winstead or NewAela), which is worldd's default for the Riverlands.

Each holds the stage counts (points, area points and sets, filtered, no template, spawned ...), the points dropped by reason, the NPCs by Blueprint, the NPCs by zone (zone mode) and a
digest of the spawned list (the multiset of x and y in cm, level and Blueprint, FNV-1a).  tests/test_worldd_region.cpp compares worldd's own run to it.

    python tools/capture/gen_pop_golden.py [--content-db PATH] [--motion PATH]          # rewrite the header (about a minute)
    python tools/capture/gen_pop_golden.py --check                                       # write nothing, exit 1 on a change

Inputs: dist/content/content.db, dist/content/npc_motion.tsv, spawns/area_spawns.h (the NPC templates retail opened), fixtures/region/*.json.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pop_oracle as P  # noqa: E402

ROOT = P.ROOT
HEADER = os.path.join(ROOT, 'server', 'worldd', 'tests', 'pop_golden_region.h')
SPAWNS = os.path.join(ROOT, 'server', 'worldd', 'spawns', 'area_spawns.h')
HOUR = 11.0

STAGE = ['placements', 'points_in_area', 'area_points', 'area_sets', 'no_asset', 'no_template', 'spawned', 'area_spawned']


def run(d, region, zoi):
    ctx = P.Context(HOUR)
    st, filt, byarch, byzoi, spawned = P.select(d, region.contains, region.zoi if zoi else (lambda x, y: 0), ctx)
    return st, filt, byarch, byzoi, spawned


def render(results, zois):
    out = ['''// ============================================================================
//  server/worldd/tests/pop_golden_region.h
//
//  GENERATED by tools/capture/gen_pop_golden.py from tools/capture/pop_oracle.py (an independent Python port of the selection); do not edit.
//
//  The Riverlands' population as the oracle counts it, for the spawn context of the tests (Wilderness, Kaelar, Summer, clear, hour 11, only Guard_Soldier among the humanoids).
//  kGoldenPlain: no zone of influence (a filter that names zones never passes: the research's pop.py).  kGoldenZoi: the point's own zone answers the filter's zones.
// ============================================================================
#pragma once

#include <cstddef>
#include <cstdint>

namespace aoc::worldd::tests {

struct GoldenCount {
    const char* name;
    uint64_t    value;
};

struct PopGolden {
    const GoldenCount* stage;       size_t stage_count;        // placements, points_in_area, area_points, area_sets, no_asset, no_template, spawned, area_spawned
    const GoldenCount* filtered;    size_t filtered_count;     // points dropped, by the Why name
    const GoldenCount* blueprints;  size_t blueprint_count;    // NPCs by Blueprint leaf
    const GoldenCount* zones;       size_t zone_count;         // NPCs by zone of influence name (zone mode only)
    uint64_t           digest;                                 // the multiset of (round(x), round(y), level, Blueprint), FNV-1a each, summed
};
''']
    for name, (st, filt, byarch, byzoi, spawned) in results:
        out.append('inline constexpr GoldenCount k%sStage[] = {' % name)
        for k in STAGE:
            out.append('    {"%s", %d},' % (k, st[k]))
        out.append('};')
        out.append('inline constexpr GoldenCount k%sFiltered[] = {' % name)
        for k in sorted(filt):
            out.append('    {"%s", %d},' % (k, filt[k]))
        out.append('};')
        out.append('inline constexpr GoldenCount k%sBlueprints[] = {' % name)
        for k in sorted(byarch):
            out.append('    {"%s", %d},' % (k, byarch[k]))
        out.append('};')
        out.append('inline constexpr GoldenCount k%sZones[] = {' % name)
        if byzoi:
            for guid, zname in zois:
                out.append('    {"%s", %d},' % (zname, byzoi.get(guid, 0)))
        else:
            out.append('    {"", 0},')
        out.append('};')
        out.append('inline constexpr PopGolden kGolden%s = {k%sStage, sizeof(k%sStage) / sizeof(GoldenCount), k%sFiltered, sizeof(k%sFiltered) / sizeof(GoldenCount), '
                   'k%sBlueprints, sizeof(k%sBlueprints) / sizeof(GoldenCount), k%sZones, %s, %dull};\n'
                   % (name, name, name, name, name, name, name, name, ('sizeof(k%sZones) / sizeof(GoldenCount)' % name) if byzoi else '0', P.digest(spawned)))
    out.append('}  // namespace aoc::worldd::tests\n')
    return '\n'.join(out)
# -- C-O-A & C:Y:B --


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--content-db', default=os.environ.get('AOC_CONTENT_DB') or os.path.join(ROOT, 'dist', 'content', 'content.db'))
    ap.add_argument('--motion', default=os.path.join(ROOT, 'dist', 'content', 'npc_motion.tsv'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    for p in (a.content_db, a.motion):
        if not os.path.exists(p):
            sys.exit('not found: ' + p)
    d = P.Data(a.content_db, a.motion, SPAWNS)
    region = P.Region()
    results = []
    for name, zoi in (('Plain', False), ('Zoi', True)):
        r = run(d, region, zoi)
        st, filt, byarch, byzoi, spawned = r
        print('%s: %s spawned, %d points in the footprint, %d area points, %d filtered, %d no template' %
              (name, st['spawned'], st['points_in_area'], st['area_points'], sum(filt.values()), st['no_template']))
        results.append((name, r))
    zois = [(g, n) for g, n, _ in region.zois]
    text = render(results, zois)
    old = open(HEADER, newline='').read() if os.path.exists(HEADER) else None
    same = old is not None and old.replace('\r\n', '\n') == text
    if a.check:
        print('pop_golden_region.h: ' + ('unchanged' if same else 'WOULD CHANGE'))
        sys.exit(0 if same else 1)
    if same:
        print('pop_golden_region.h: unchanged')
        return
    crlf = old is not None and '\r\n' in old
    with open(HEADER, 'w', newline='') as f:
        f.write(text.replace('\n', '\r\n') if crlf else text)
    print('pop_golden_region.h: updated')


if __name__ == '__main__':
    main()
