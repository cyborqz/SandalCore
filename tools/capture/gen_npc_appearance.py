"""server/worldd/tests/npc_appearance_key.h: which NPC Blueprints the retail captures open with an NPCAppearanceComponent (plan E1, stage 3, the spawn filter).

The answer key of "Blueprints with no valid visuals" (spawns/spawn_filter.h).  A humanoid's body is merged at run time from an NPCAppearanceComponent
(UNPCAppearanceComponent, a dynamic subobject of the open); a creature's is the Blueprint's own mesh.  An NPC opened without the component whose Blueprint
needs one shows invisible (the villagers and quest masters of the stage-2 run).  The table counts, per Blueprint class name, the retail opens of the captures
and how many carried the component; tools/mapc reads the Blueprints' meshes (npc_motion.tsv: SK_PC_MASTER, the player's master mesh, is the merged body), and
test_worldd_spawn_filter holds the two against each other: of the 172 Blueprints the captures open, 92 carry the component in most opens and all 92 have
SK_PC_MASTER, the other 80 never carry one and have another mesh.

The input is the research scan of the 1,105 unique retail captures (one JSON per capture: its actor epochs with their subobject class exports), read from
--scan DIR or AOC_ACTORS_SCAN (it lives in the research scratchpad, research/actors/scan, and is not in the repository).  Without it `--check` has nothing
to compare and says so (exit 0); with it, a stale header exits 1.

    python tools/capture/gen_npc_appearance.py --scan DIR           # rewrite the header
    python tools/capture/gen_npc_appearance.py --scan DIR --check   # write nothing, exit 1 on a change
"""
import argparse
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADER = os.path.join(ROOT, 'server', 'worldd', 'tests', 'npc_appearance_key.h')


def leaf_of(path):
    leaf = path.split('/')[-1].split('.')[0]
    return leaf

# (C | Y | B + C O A)

def collect(scan_dir):
    table = {}
    files = sorted(glob.glob(os.path.join(scan_dir, '*.json')), key=lambda p: int(os.path.splitext(os.path.basename(p))[0]))
    for f in files:
        with open(f, encoding='utf-8') as fh:
            d = json.load(fh)
        for e in d['epochs']:
            path = e.get('arch_path') or ''
            if '/Population/NPC/' not in path:
                continue
            has = any('NPCAppearanceComponent' in (s.get('cls') or '') for s in e.get('subs', []))
            row = table.setdefault(leaf_of(path), [0, 0])
            row[0] += 1
            row[1] += 1 if has else 0
    return files, table


def render(files, table):
    out = []
    out.append('// Generated by tools/capture/gen_npc_appearance.py from the research scan of %d retail captures: do not edit.' % len(files))
    out.append('// Per Blueprint class name the retail opens (epochs) of NPCs under /Population/NPC/ and how many carried an NPCAppearanceComponent.')
    out.append('#pragma once')
    out.append('')
    out.append('namespace aoc::worldd::tests {')
    out.append('')
    out.append('struct NpcAppearanceEvidence {')
    out.append('    const char* leaf;')
    out.append('    int         epochs;')
    out.append('    int         with_component;')
    out.append('};')
    out.append('')
    out.append('inline constexpr NpcAppearanceEvidence kNpcAppearanceEvidence[] = {')
    for leaf in sorted(table):
        n, h = table[leaf]
        out.append('    {"%s", %d, %d},' % (leaf, n, h))
    out.append('};')
    out.append('')
    out.append('}  // namespace aoc::worldd::tests')
    return '\r\n'.join(out) + '\r\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--scan', default=os.environ.get('AOC_ACTORS_SCAN', ''))
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    if not args.scan or not os.path.isdir(args.scan):
        if args.check:
            print('npc_appearance_key.h: no scan folder (--scan or AOC_ACTORS_SCAN): not checked')
            return 0
        print('error: --scan DIR (or AOC_ACTORS_SCAN) is needed', file=sys.stderr)
        return 2
    files, table = collect(args.scan)
    text = render(files, table)
    old = open(HEADER, 'rb').read().decode('utf-8') if os.path.exists(HEADER) else ''
    if args.check:
        if old != text:
            print('npc_appearance_key.h: WOULD CHANGE (%d Blueprints)' % len(table))
            return 1
        print('npc_appearance_key.h: unchanged (%d Blueprints)' % len(table))
        return 0
    with open(HEADER, 'wb') as fh:
        fh.write(text.encode('utf-8'))
    print('wrote %s: %d Blueprints from %d captures' % (HEADER, len(table), len(files)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
