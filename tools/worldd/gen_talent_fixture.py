"""Writes server/worldd/tests/talent_fixture.sql from a content.db (read only): the real rows worldd's talents catalog reads for the eight
class trees, the Universal tree, the 14 weapon trees and the gathering trees whose ranks a character has from the start, with the points
each level gives, the ranks' abilities, effects and costs, the constant stat mods of their infinite effects and the combo ability of the
starting kits' weapons -- so that worldd's tests run the real talent rules on the real trees without the 275 MB file.

    python tools/worldd/gen_talent_fixture.py [content.db] [talent_fixture.sql]

The defaults are dist/content/content.db and server/worldd/tests/talent_fixture.sql of the repository. It needs a content.db of contentc
version 5 with plan D1's stage 2 tables (skill_tree, skill_node, ... item_weapon). The file is the table definitions (copied from the
database's own sqlite_master) and one INSERT per row; content_db_fixture.h runs it (TALENT_FIXTURE_PATH, defined by CMake)."""
import os
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DB = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'dist', 'content', 'content.db')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'server', 'worldd', 'tests', 'talent_fixture.sql')
con = sqlite3.connect('file:%s?mode=ro' % DB.replace('\\', '/'), uri=True)


def lit(v):
    if v is None:
        return 'NULL'
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    if isinstance(v, float):
        return repr(v)
    return str(v)


TABLES = ['skill_point_type', 'leveling_point', 'skill_tree', 'skill_node', 'skill_node_require', 'skill_node_exclusive', 'skill_rank',
          'skill_rank_cost', 'skill_rank_stat_mod', 'item_weapon']

trees = [r[0] for r in con.execute('''
    SELECT guid FROM skill_tree WHERE kind IN ('class', 'universal', 'weapon')
       OR (kind = 'profession' AND EXISTS (SELECT 1 FROM skill_node n WHERE n.tree_guid = skill_tree.guid AND n.auto_granted = 1 AND n.level_requirement <= 1))
    ORDER BY guid''')]
tree_list = ','.join(map(str, trees))
types = [r[0] for r in con.execute(f'SELECT DISTINCT leveling_type_guid FROM skill_tree WHERE guid IN ({tree_list}) ORDER BY 1')]
skills = [r[0] for r in con.execute(f'SELECT DISTINCT skill_guid FROM skill_node WHERE tree_guid IN ({tree_list}) ORDER BY 1')]
skill_list = ','.join(map(str, skills))
ranks = [r[0] for r in con.execute(f'SELECT DISTINCT rank_guid FROM skill_rank WHERE skill_guid IN ({skill_list}) ORDER BY 1')]
rank_list = ','.join(map(str, ranks))
kit_items = [r[0] for r in con.execute('SELECT DISTINCT item_guid FROM starting_equipment ORDER BY 1')]
item_list = ','.join(map(str, kit_items))

QUERIES = {
    'skill_point_type': 'SELECT * FROM skill_point_type ORDER BY guid',
    'leveling_point': f'SELECT * FROM leveling_point WHERE type_guid IN ({",".join(map(str, types))}) ORDER BY type_guid, level, point_type_guid',
    'skill_tree': f'SELECT * FROM skill_tree WHERE guid IN ({tree_list}) ORDER BY guid',
    'skill_node': f'SELECT * FROM skill_node WHERE tree_guid IN ({tree_list}) ORDER BY tree_guid, ord',
    'skill_node_require': f'SELECT * FROM skill_node_require WHERE tree_guid IN ({tree_list}) ORDER BY tree_guid, node_guid, ord',
    'skill_node_exclusive': f'SELECT * FROM skill_node_exclusive WHERE tree_guid IN ({tree_list}) ORDER BY tree_guid, node_guid, ord',
    'skill_rank': f'SELECT * FROM skill_rank WHERE skill_guid IN ({skill_list}) ORDER BY skill_guid, ord',
    'skill_rank_cost': f'SELECT * FROM skill_rank_cost WHERE rank_guid IN ({rank_list}) ORDER BY rank_guid, ord',
    'skill_rank_stat_mod': f'SELECT * FROM skill_rank_stat_mod WHERE rank_guid IN ({rank_list}) ORDER BY rank_guid, ord',
    'item_weapon': f'SELECT * FROM item_weapon WHERE item_guid IN ({item_list}) ORDER BY item_guid',
}
# (C O A) (C Y B)

lines = ['-- GENERATED by tools/worldd/gen_talent_fixture.py from a content.db (contentc version 5, plan D1 stage 2); do not edit.',
         '-- The real rows of the talents catalog for the class, Universal, weapon and gathering trees (see the generator).']
# skill_rank_stat_mod is a plan D1 stage 1 table: the fixture makes it itself (with its own rows for the stage 1 tests), these rows replace them
OWNED_BY_FIXTURE = {'skill_rank_stat_mod'}
for t in TABLES:
    if t not in OWNED_BY_FIXTURE:
        ddl = con.execute("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?", (t,)).fetchone()[0]
        lines.append(ddl.strip() + ';')
        for row in con.execute("SELECT sql FROM sqlite_master WHERE type = 'index' AND tbl_name = ? AND sql IS NOT NULL", (t,)):
            lines.append(row[0].strip() + ';')
    cols = [c[1] for c in con.execute(f'PRAGMA table_info({t})')]
    verb = 'INSERT OR REPLACE' if t in OWNED_BY_FIXTURE else 'INSERT'
    for r in con.execute(QUERIES[t]):
        lines.append('%s INTO %s (%s) VALUES (%s);' % (verb, t, ', '.join(cols), ', '.join(lit(x) for x in r)))
text = '\n'.join(lines) + '\n'
with open(OUT, 'w', newline='\n', encoding='utf-8') as f:
    f.write(text)
print('%s: %d trees, %d skills, %d ranks, %d lines, %d bytes' % (OUT, len(trees), len(skills), len(ranks), len(lines), len(text)))
