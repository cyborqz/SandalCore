"""Writes server/worldd/tests/retail_purchases.h: every ServerPurchaseSkillBuild request of the retail captures (128 calls, 411 entries), as the
Guids the client sent, so that worldd's tests can run the validator on what the real client asks for.

    python tools/worldd/gen_retail_purchases.py <requests.json> [retail_purchases.h]

requests.json is a list of {"cap": capture number, "line": line of the request in the capture, "changes": [{"rank", "tree", "lt", "buy"}],
"after": [rank Guids]} with the three Guids of each entry (SkillRank, SkillTree, LevelingType) and bPurchase; the decoder's own extract of each
capture (p2/ex2/<n>.json: the rpcs named ServerPurchaseSkillBuild, direction C>S, parameter BuildChanges.AllocationChanges) has them. "after" is
the tree list the server answered with (the ULevelingComponent's SkillTreePurchasesFastMap item of the one tree the call touches): what the
character owned once the call was done, so that the test knows what it owned before (the list without the call's purchases, with its refunds).
The order of the calls is the capture's."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1]
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'server', 'worldd', 'tests', 'retail_purchases.h')
calls = json.load(open(SRC))
# C:Y:B - CoA

lines = ['// GENERATED by tools/worldd/gen_retail_purchases.py from the retail captures (the ServerPurchaseSkillBuild requests); do not edit.',
         '// %d calls, %d entries. Each call: the capture, the line of the request, its entries (rank, tree, LevelingType Guids, bPurchase).' %
         (len(calls), sum(len(c['changes']) for c in calls)),
         '#pragma once',
         '',
         '#include <cstddef>',
         '#include <cstdint>',
         '',
         'namespace retail_purchases {',
         '',
         'struct Entry {',
         '    int64_t rank, tree, leveling_type;',
         '    bool    purchase;',
         '};',
         'struct Call {',
         '    int    capture, line;',
         '    size_t first, count;               // the entries, into kEntries',
         '    size_t after_first, after_count;   // the tree list the server answered with, into kAfter',
         '};',
         '',
         'inline constexpr Entry kEntries[] = {']
for c in calls:
    for e in c['changes']:
        lines.append('    {%dll, %dll, %dll, %s},' % (e['rank'], e['tree'], e['lt'], 'true' if e['buy'] else 'false'))
lines.append('};')
lines.append('')
lines.append('inline constexpr int64_t kAfter[] = {')
for c in calls:
    for r in c['after']:
        lines.append('    %dll,' % r)
lines.append('};')
lines.append('')
lines.append('inline constexpr Call kCalls[] = {')
first = 0
after = 0
for c in calls:
    n = len(c['changes'])
    lines.append('    {%d, %d, %d, %d, %d, %d},' % (c['cap'], c['line'], first, n, after, len(c['after'])))
    first += n
    after += len(c['after'])
lines.append('};')
lines.append('')
lines.append('}  // namespace retail_purchases')
open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('%s: %d calls, %d entries' % (OUT, len(calls), first))
