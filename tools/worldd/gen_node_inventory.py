"""Writes server/worldd/world/node_inventory_table.h from dist/content/content.db.

A node's stores: what it starts with and the goods a game master may put in them.  contentc keeps neither, so this reads the raw records:

  the start   each CityNodeRecordBase's InitialNodeResourcesId names a NodeInventoryContentsRecordBase: its CurrencyValues (the Money currency's
              amount, copper) and its StoredItems (an item record and a quantity each).  Default_InitialNodeResources is 1,525,050 copper and
              225 each of Commodity_T1_Materials, _Tools and _Food.
  the goods   each CommodityDefRecordBase and the item it makes (CommodityProducedId): ServerGMAddNodeItem names a commodity by its def's name.
              A def that makes no item is left out.

Run from the repository root; `--out FILE` writes elsewhere.
"""
import gzip
import json
import sqlite3
import sys

DB = "dist/content/content.db"
OUT = "server/worldd/world/node_inventory_table.h"
MONEY = 6064629127873626112   # the CurrencyTierDefRecordBase "Money": copper


def records(db, schema):
    for guid, name, data in db.execute("select guid, name, data from record where schema = ? order by guid", (schema,)):
        yield guid, name, json.loads(gzip.decompress(data))


def main():
    out_path = OUT
    if "--out" in sys.argv:
        out_path = sys.argv[sys.argv.index("--out") + 1]
    db = sqlite3.connect(DB)
    contents = {}
    for guid, name, d in records(db, "NodeInventoryContentsRecordBase"):
        money = sum(int(c.get("Value", 0)) for c in d.get("CurrencyValues", []) if c.get("Key", {}).get("Guid") == MONEY)
        items = [(int(s["ItemId"]["Guid"]), int(s.get("Quantity", 0))) for s in d.get("StoredItems", []) if s.get("ItemId", {}).get("Guid")]
        contents[guid] = (name, money, items)
    nodes = []
    for guid, name, d in records(db, "CityNodeRecordBase"):
        ref = (d.get("InitialNodeResourcesId") or {}).get("Guid", 0)
        if ref and ref in contents:
            nodes.append((guid, name, ref))
    goods = []
    for guid, name, d in records(db, "CommodityDefRecordBase"):
        item = (d.get("CommodityProducedId") or {}).get("Guid", 0)
        if item:
            goods.append((name, guid, int(item)))
    goods.sort()

    item_rows, starts = [], []
    for ref, (name, money, items) in sorted(contents.items()):
        first = len(item_rows)
        item_rows.extend(items)
        starts.append((ref, name, money, first, len(items)))
    index = {ref: i for i, (ref, *_rest) in enumerate(starts)}

    lines = [
        "// SPDX-License-Identifier: AGPL-3.0-only",
        "// Copyright (C) 2026 Cyb and contributors. Developed by Cyb; thanks to Hatemost and CoA (Creation of Ashes).",
        "// Generated by tools/worldd/gen_node_inventory.py from content.db.  Do not edit.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace aoc::worldd::world::node_inventory {",
        "",
        "struct StoredItem {",
        "    int64_t item;",
        "    int32_t quantity;",
        "};",
        "/// A NodeInventoryContentsRecordBase: its Money (copper) and the items kStoredItems[first .. first + count) hold.",
        "struct Contents {",
        "    int64_t     record;",
        "    const char* name;",
        "    int64_t     money;",
        "    size_t      first, count;",
        "};",
        "/// A city node and the contents it starts with (CityNodeRecordBase.InitialNodeResourcesId): kContents[contents].",
        "struct NodeStart {",
        "    int64_t     node;",
        "    const char* name;",
        "    size_t      contents;",
        "};",
        "/// A CommodityDefRecordBase and the item it makes (CommodityProducedId).",
        "struct Commodity {",
        "    const char* name;",
        "    int64_t     def;",
        "    int64_t     item;",
        "};",
        "",
        "inline constexpr StoredItem kStoredItems[] = {",
    ]
    for item, quantity in item_rows:
        lines.append(f"    {{{item}ll, {quantity}}},")
    if not item_rows:
        lines.append("    {0, 0},")
    lines.append("};")
    lines.append("inline constexpr Contents kContents[] = {")
    for ref, name, money, first, count in starts:
        lines.append(f'    {{{ref}ll, "{name}", {money}ll, {first}, {count}}},')
    lines.append("};")
    lines.append("inline constexpr NodeStart kNodeStarts[] = {")
    for guid, name, ref in nodes:
        lines.append(f'    {{{guid}ll, "{name}", {index[ref]}}},')
    lines.append("};")
    lines.append("inline constexpr Commodity kCommodities[] = {")
    for name, guid, item in goods:
        lines.append(f'    {{"{name}", {guid}ll, {item}ll}},')
    lines.append("};")
    lines += ["", "}  // namespace aoc::worldd::world::node_inventory", ""]
    open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(f"{out_path}: {len(starts)} contents ({len(item_rows)} items), {len(nodes)} nodes that start with one, {len(goods)} commodities")


if __name__ == "__main__":
    main()
