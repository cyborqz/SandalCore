"""Writes server/worldd/tests/gear_fixture.h from a content.db (read only): the real rows the stat engine needs for the
eight classes' starting kits (item records, stat blocks, quality curve, tags, sets, EEquipSlot names, the classes), so that
worldd's tests can run the real stat program on the real kits without the 275 MB file.

    python tools/worldd/gen_gear_fixture.py [content.db] [gear_fixture.h]

The defaults are dist/content/content.db and server/worldd/tests/gear_fixture.h of the repository. It needs a content.db of
contentc version 4 (plan B3: quality_curve, stat_block_stat, item_set, set_bonus, item_tag)."""
import os
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DB = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'dist', 'content', 'content.db')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'server', 'worldd', 'tests', 'gear_fixture.h')
con = sqlite3.connect('file:%s?mode=ro' % DB.replace('\\', '/'), uri=True)


def lit(v):
    if v is None:
        return 'NULL'
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    if isinstance(v, float):
        return repr(v)
    return str(v)


stmts = []


def rows(table, cols, query, args=(), verb='INSERT OR REPLACE'):
    for r in con.execute(query, args):
        stmts.append('%s INTO %s (%s) VALUES (%s)' % (verb, table, ', '.join(cols), ', '.join(lit(x) for x in r)))


kits = {}
for cls, in con.execute("select distinct class_name from starting_equipment order by class_name"):
    kits[cls] = [(slot, item) for slot, item in con.execute(
        "select slot, item_guid from starting_equipment where class_name=? and container='Equipment' order by ord", (cls,))]
items = sorted({i for k in kits.values() for _, i in k})
q = ','.join(map(str, items))
blocks = sorted({r[0] for r in con.execute(f"select stat_block_guid from item where guid in ({q}) and stat_block_guid<>0")})
curves = sorted({r[0] for r in con.execute(f"select quality_curve_guid from item where guid in ({q}) and quality_curve_guid<>0")})
sets = sorted({r[0] for r in con.execute(f"select set_guid from item_set where item_guid in ({q})")})

rows('equip_slot', ['slot', 'name'], 'select slot, name from equip_slot order by slot')
rows('class', ['guid', 'name', 'archetype_id'], 'select guid, name, archetype_id from class order by guid')
rows('item', ['guid', 'name', 'level', 'can_equip', 'occupies_all_equip_slots', 'default_quality', 'stat_block_guid', 'quality_curve_guid'],
     f'select guid, name, level, can_equip, occupies_all_equip_slots, default_quality, stat_block_guid, quality_curve_guid from item where guid in ({q}) order by guid')
rows('item_equip_slot', ['item_guid', 'ord', 'slot'], f'select item_guid, ord, slot from item_equip_slot where item_guid in ({q}) order by item_guid, ord', verb='INSERT OR IGNORE')
if curves:
    rows('quality_curve', ['guid', 'ord', 'x', 'y'], 'select guid, ord, x, y from quality_curve where guid in (%s) order by guid, ord' % ','.join(map(str, curves)))
cols = ['block_guid', 'stat_guid'] + [f'{r}_{m}' for r in ('common', 'uncommon', 'rare', 'heroic', 'epic', 'legendary', 'artifact') for m in ('min', 'max')]
if blocks:
    rows('stat_block_stat', cols, 'select %s from stat_block_stat where block_guid in (%s) order by block_guid, stat_guid' % (', '.join(cols), ','.join(map(str, blocks))))
rows('item_tag', ['item_guid', 'ord', 'tag'], f'select item_guid, ord, tag from item_tag where item_guid in ({q}) order by item_guid, ord')
rows('item_set', ['item_guid', 'ord', 'set_guid'], f'select item_guid, ord, set_guid from item_set where item_guid in ({q}) order by item_guid, ord')
if sets:
    rows('set_bonus', ['set_guid', 'tier_ord', 'pieces', 'bonus_ord', 'stat_guid', 'common', 'uncommon', 'rare', 'heroic', 'epic', 'legendary', 'artifact'],
         'select set_guid, tier_ord, pieces, bonus_ord, stat_guid, common, uncommon, rare, heroic, epic, legendary, artifact from set_bonus where set_guid in (%s) order by set_guid, tier_ord, bonus_ord' % ','.join(map(str, sets)))
# -- Cyb & C.O.A --

classes = {name: (guid, arche) for guid, name, arche in con.execute('select guid, name, archetype_id from class')}
enum = {'Ranger': 1, 'Bard': 2, 'Cleric': 3, 'Fighter': 4, 'Rogue': 5, 'Summoner': 6, 'Tank': 7, 'Mage': 8}

with open(OUT, 'w', newline='\n') as f:
    f.write('''// ============================================================================
//  server/worldd/tests/gear_fixture.h
//
//  GENERATED by tools/worldd/gen_gear_fixture.py from a content.db (contentc version 4); do not edit.
//
//  The real rows the stat engine reads for the eight classes' starting kits (plan B3): EEquipSlot names, the eight classes, the
//  kits' item records with their stat blocks, quality curve, tags and sets. With them the fixture content.db (content_db_fixture.h)
//  lets the tests run the real stat program on the real kits without the 275 MB file: the stats of each class's level-1 kit then
//  equal the corpus's `kit_<class>_l1` case, and the captured Bard's equal pkt#107.
// ============================================================================
#pragma once

#include <cstdint>

namespace gear_fixture {

struct KitItem {
    int     slot;      // the EEquipSlot value
    int64_t record;    // the ItemRecord Guid; its quality is the record's default (1)
};

/// One statement each, run in order after the tables are created.
inline constexpr const char* kStatements[] = {
''')
    for s in stmts:
        f.write('    "%s",\n' % s)
    f.write('};\n\n')
    for cls in sorted(kits, key=lambda c: enum[c]):
        f.write('inline constexpr KitItem k%sKit[] = {\n' % cls)
        for slot, item in kits[cls]:
            f.write('    {%d, %dll},\n' % (slot, item))
        f.write('};\n')
    f.write('''
struct ClassKit {
    int            class_id;   // ECharacterClass
    const char*    name;
    int64_t        guid;
    const KitItem* items;
    int            count;
};
inline constexpr ClassKit kClassKits[] = {
''')
    for cls in sorted(kits, key=lambda c: enum[c]):
        f.write('    {%d, "%s", %dll, k%sKit, %d},\n' % (enum[cls], cls, classes[cls][0], cls, len(kits[cls])))
    f.write('};\n\n}  // namespace gear_fixture\n')
print(len(stmts), 'statements;', {c: len(k) for c, k in kits.items()}, len(items), 'items', len(blocks), 'blocks', len(curves), 'curves', len(sets), 'sets')
