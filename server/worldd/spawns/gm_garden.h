//  spawns/gm_garden.h  (G1, stage 1, Part B)
//
//  The GM garden: a handful of resource nodes near the login spot, one for each gathering profession (Mining, Lumberjacking, Herbalism) and certification tier
//  (Novice to GrandMaster), so that the user can try every tier in stage 2 without walking the country for them.  It is a test aid: worldd places it only with
//  `--gm-garden` (or AOC_GM_GARDEN=1) and leaves it out by default.
//
//    the nodes    each is a REAL GatherableActorDef of the design data (spawns/garden_defs.h, generated by tools/capture/gen_gm_garden.py from content.db).  The
//                 data has an actor node at Novice, Apprentice and Journeyman for all three professions and at GrandMaster for Herbalism only: 10 of the 15
//                 slots.  The other five (Master for the three professions, GrandMaster for Mining and Lumberjacking) are painted foliage or nothing in the game's
//                 data, not an actor; they are listed in the log and in the report, and nothing stands in for them.
//    the made     a node is made from a retail gatherable open (a captured node, any: they are all Default__GatherableActor), with the def's Guid in the actor
//                 block and the def's PlayerInteractionDef in the first input of its InteractableComponent, a new GatherableGuid, and the garden's position.  It is
//                 VISIBLE ONLY: gathering is stage 2 (the interaction is the retail one of its def, and worldd answers it with nothing yet).
//    the place    30 to 60 m from the login spot, on the ground (the navmesh's or the terrain's height; the login spot's height where there is no ground file),
//                 each profession in a sector of its own, the tiers outwards along it; never within 6 m of another actor (an NPC, a vendor, a captured node) or 8 m
//                 of another garden node: a candidate that is too close is moved along the ring and then outwards.  The same world places the same garden.
//
//  Pure setup, like spawns/area_loader.h: nothing here sends anything or reads a clock; the registry is the only thing changed.
// ============================================================================
#pragma once

#include "spawns/area.h"
#include "spawns/captured_spawns.h"
#include "spawns/garden_defs.h"
#include "world/actor_registry.h"

#include <cstdint>
#include <functional>
#include <string>
#include <vector>

namespace aoc::worldd::spawns {

/// The nearest garden distance from the login spot (cm), the farthest, and the clearances.
inline constexpr double kGardenMinCm = 3000.0, kGardenMaxCm = 6000.0;
inline constexpr double kGardenActorClearCm = 600.0, kGardenNodeClearCm = 800.0;

/// A ground answer: the height of the ground under (x, y) near `z_hint`; false when there is none.
using GardenGround = std::function<bool(double x, double y, double z_hint, double* z)>;

struct GardenNode {
    const garden::Def* def = nullptr;
    uint64_t           actor_id = 0;
    double             x = 0, y = 0, z = 0, yaw = 0;
    bool               grounded = false;       // z is a ground's, not the login spot's height
};
// [Cyb - C-O-A]

struct GardenReport {
    std::vector<GardenNode> nodes;
    size_t                  gaps = 0;           // the profession and tier slots the data has no actor node for (garden::kGardenGaps)
    size_t                  unplaced = 0;       // defs for which no free place was found (or that were refused)
    std::vector<std::string> notes;
    /// A few lines for the log.
    std::string describe() const;
};

/// Places the garden into `registry`.  `donor` is the open every node is made from (any captured gatherable: null makes no garden and says so in the notes).  `ground`
/// may be empty (the login spot's height is used and the nodes say so).
GardenReport place_gm_garden(world::ActorRegistry& registry, const OpenTemplate* donor, const AreaConfig& area, const Minter& mint, uint32_t server_id, double world_time,
                             const GardenGround& ground);

/// The first captured gatherable open of `captured` (null when there is none).
const OpenTemplate* garden_donor(const CapturedData& captured);

}  // namespace aoc::worldd::spawns
